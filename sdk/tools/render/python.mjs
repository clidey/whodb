// render/python.mjs — Python renderer for generate-core.mjs. Emits the
// generated wire core consumed by the handwritten whodb package. Operations
// are transport-agnostic request builders so the sync and async clients share
// all generated code.
import { isEnumType, isScalarType, isInputObjectType, isObjectType, isNonNullType, isListType, getNamedType } from 'graphql';

const SCALAR_PY = {
  ID: 'str',
  String: 'str',
  Int: 'int',
  Float: 'float',
  Boolean: 'bool',
};

function header(ir) {
  return `# GENERATED by sdk/tools/generate-core.mjs — DO NOT EDIT (manifest ${ir.manifestHash.slice(0, 12)})\n`;
}

function pyTypeOf(gqlType, ir) {
  if (isNonNullType(gqlType)) return pyTypeOfInner(gqlType.ofType, false, ir);
  return pyTypeOfInner(gqlType, true, ir);
}

function pyTypeOfInner(gqlType, nullable, ir) {
  let py;
  if (isListType(gqlType)) {
    py = `list[${pyTypeOf(gqlType.ofType, ir)}]`;
  } else {
    const named = getNamedType(gqlType);
    if (SCALAR_PY[named.name]) {
      py = SCALAR_PY[named.name];
    } else if (isScalarType(named)) {
      py = 'Any';
    } else if (isEnumType(named)) {
      py = 'str';
    } else {
      // Forward reference — all generated TypedDicts live in this module.
      py = `"${named.name}"`;
    }
  }
  return nullable ? `Optional[${py}]` : py;
}

function renderTypes(ir) {
  const lines = [header(ir)];
  lines.push('from __future__ import annotations');
  lines.push('');
  lines.push('from typing import Any, Optional, TypedDict');
  lines.push('');
  const sorted = [...ir.typeClosure].sort();
  for (const name of sorted) {
    const type = ir.schema.getType(name);
    if (!type) continue;
    if (isEnumType(type)) {
      // Enums travel as strings on the wire; alias for readability.
      lines.push(`${name} = str  # enum: ${type.getValues().map(v => v.name).join(' | ')}`);
      lines.push('');
      continue;
    }
    if (isInputObjectType(type) || isObjectType(type)) {
      // Functional TypedDict syntax: GraphQL field names may be Python
      // keywords (e.g. "as"), which the class syntax cannot express.
      const fields = Object.values(type.getFields())
        .map(f => `        "${f.name}": ${pyTypeOf(f.type, ir)},`)
        .join('\n');
      lines.push(`#: GraphQL type ${name}.`);
      lines.push(`${name} = TypedDict(`);
      lines.push(`    "${name}",`);
      lines.push('    {');
      lines.push(fields || '');
      lines.push('    },');
      lines.push('    total=False,');
      lines.push(')');
      lines.push('');
    }
  }
  return lines.join('\n') + '\n';
}

function snakeCase(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
}

function renderOperations(ir) {
  const lines = [header(ir)];
  lines.push('from __future__ import annotations');
  lines.push('');
  lines.push('from typing import Any');
  lines.push('');
  lines.push('');
  lines.push('class Request:');
  lines.push('    """One prepared platform operation: document + variables."""');
  lines.push('');
  lines.push('    def __init__(self, operation: str, document: str, variables: dict[str, Any]):');
  lines.push('        self.operation = operation');
  lines.push('        self.document = document');
  lines.push('        self.variables = variables');
  lines.push('');

  for (const op of ir.operations) {
    const fnName = snakeCase(op.name);
    lines.push('');
    lines.push(`${op.name.toUpperCase()}_DOCUMENT = ${JSON.stringify(op.document)}`);
    lines.push('');
    lines.push('');
    lines.push(`def ${fnName}_request(variables: dict[str, Any]) -> Request:`);
    lines.push(`    """Build the wire request for ${op.kind} ${op.name}."""`);
    lines.push(`    return Request("${op.name}", ${op.name.toUpperCase()}_DOCUMENT, variables)`);
    lines.push('');
    lines.push('');
    lines.push(`def ${fnName}_parse(data: dict[str, Any]) -> Any:`);
    lines.push(`    """Extract the ${op.name} payload from a GraphQL data object."""`);
    lines.push(`    return data.get("${op.name}")`);
  }
  return lines.join('\n') + '\n';
}

function renderManifest(ir) {
  const entries = {};
  for (const op of ir.operations) {
    entries[op.name] = {
      kind: op.kind,
      ...(op.deprecated ? { deprecated: true } : {}),
      ...(op.sunsetAt ? { sunsetAt: op.sunsetAt } : {}),
      ...(op.behaviorChanged ? { behaviorChanged: true } : {}),
      ...(op.note ? { note: op.note } : {}),
    };
  }
  return (
    header(ir) +
    `"""Per-operation versioning-policy state embedded at generation time."""\n\n` +
    `EMBEDDED_MANIFEST = ${JSON.stringify(entries, null, 4).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False')}\n\n` +
    `MANIFEST_HASH = "${ir.manifestHash}"\n\n` +
    `MANIFEST_PROTOCOL_VERSION = "${ir.protocolVersion}"\n`
  );
}

function renderHydration(ir) {
  return (
    header(ir) +
    `"""Column-type → coercion kind rules shared across all SDK languages."""\n\n` +
    `HYDRATION_RULES = ${JSON.stringify(ir.hydrationRules.rules, null, 4)}\n\n` +
    `HYDRATION_DEFAULT = "${ir.hydrationRules.default}"\n`
  );
}

function renderInit(ir) {
  return header(ir) + '"""Generated wire core for the whodb SDK. Do not import directly."""\n';
}

export function renderPython(ir) {
  return [
    ['__init__.py', renderInit(ir)],
    ['types.py', renderTypes(ir)],
    ['operations.py', renderOperations(ir)],
    ['manifest.py', renderManifest(ir)],
    ['hydration.py', renderHydration(ir)],
  ];
}
